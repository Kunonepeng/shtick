def artwork_sample_zoom():
    im=quality_img(1200,590);d=ImageDraw.Draw(im)
    def plot(x0,y0,w,h,pts,dots):
        d.line((x0,y0+h//2,x0+w,y0+h//2),fill=(203,203,213),width=2)
        d.line((x0,y0,x0,y0+h),fill=(171,171,177),width=3)
        xy=[]
        for i in range(pts):
            x=x0+w*i/(pts-1)
            y=y0+h/2-0.40*h*math.sin(i/(pts-1)*math.pi*5)
            xy.append((x,y))
        d.line(xy,fill=(120,120,130),width=4)
        if dots:
            for x,y in xy:d.ellipse((x-8,y-8,x+8,y+8),fill=CYAN,outline=WHITE,width=2)
    plot(45,80,480,320,260,False)
