def artwork_jpeg_compare():
    # Same exact input data, different output quality. Detail ROI is shared pixel coordinates.
    original=b.procedural_picture()
    src=io.BytesIO();original.save(src,format='JPEG',quality=3,subsampling=2,optimize=False)
    lossy=Image.open(io.BytesIO(src.getvalue())).convert('RGB')
    roi=(230,140,440,300)
    zoom_orig=original.crop(roi).resize((410,260),Image.Resampling.NEAREST)
    zoom_loss=lossy.crop(roi).resize((410,260),Image.Resampling.NEAREST)
    im=quality_img(1200,410);im.paste(zoom_orig,(90,70));im.paste(zoom_loss,(700,70))
    d=ImageDraw.Draw(im)
    for x in (80,690):d.rectangle((x,60,x+430,340),outline=PURPLE,width=5)
    return im


